using AstraFinance.Core.Entities;
using AstraFinance.Core.Enums;
using AstraFinance.Core.Rules;

namespace AstraFinance.Core.Models;

/// <summary>Input for creating an account. The opening balance is fixed after creation; use a balance adjustment to correct it.</summary>
public sealed record AccountDraft(
    string Name,
    AccountType Type,
    long OpeningBalance,
    string IconKey,
    string ColorHex);

/// <summary>Editable account fields (never the opening balance).</summary>
public sealed record AccountUpdate(string Name, AccountType Type, string IconKey, string ColorHex);

/// <summary>An account with its calculated balance.</summary>
public sealed record AccountSummary(Account Account, long Balance, BalanceComponents Components);

public sealed record CategoryDraft(string Name, CategoryKind Kind, string IconKey, string ColorHex);

/// <summary>
/// Input for creating or editing a transaction. <see cref="Id"/> is generated by the caller when the
/// form opens, so a double-submitted form is recognised and saved only once.
/// </summary>
public sealed record TransactionDraft
{
    public Guid Id { get; init; } = Guid.NewGuid();

    public TransactionType Type { get; init; }

    public long Amount { get; init; }

    public string? Description { get; init; }

    public string? Notes { get; init; }

    public Guid? CategoryId { get; init; }

    /// <summary>Income/expense account or transfer source.</summary>
    public Guid AccountId { get; init; }

    public Guid? DestinationAccountId { get; init; }

    public DateOnly Date { get; init; }

    /// <summary>Optional transfer fee, recorded as a separate Expense from the source account.</summary>
    public long TransferFee { get; init; }

    /// <summary>Expense category for the fee; defaults to the built-in "Fees" category.</summary>
    public Guid? FeeCategoryId { get; init; }
}

/// <summary>Result of saving a transaction.</summary>
/// <param name="Transaction">The saved transaction.</param>
/// <param name="Fee">The linked fee expense, when the transfer has a fee.</param>
/// <param name="WasDuplicate">True when an identical submission had already been saved and nothing new was written.</param>
public sealed record TransactionSaveResult(Transaction Transaction, Transaction? Fee, bool WasDuplicate);

public enum TransactionSort
{
    DateDescending = 0,
    DateAscending = 1,
    AmountDescending = 2,
    AmountAscending = 3,
}

/// <summary>Filters for the transaction list. Null/empty filters are not applied.</summary>
public sealed record TransactionQuery
{
    public string? Search { get; init; }

    /// <summary>
    /// With <see cref="Search"/>: also match transactions in these categories (the caller resolves
    /// localized category names, which the database doesn't know).
    /// </summary>
    public IReadOnlyCollection<Guid>? SearchCategoryIds { get; init; }

    /// <summary>With <see cref="Search"/>: also match transactions on these accounts (either side of a transfer).</summary>
    public IReadOnlyCollection<Guid>? SearchAccountIds { get; init; }

    /// <summary>With <see cref="Search"/>: also match this exact amount (minor units) when the text is a number.</summary>
    public long? SearchAmount { get; init; }

    public DateOnly? From { get; init; }

    public DateOnly? To { get; init; }

    public IReadOnlyCollection<Guid>? CategoryIds { get; init; }

    /// <summary>Matches the account on either side of a transfer.</summary>
    public IReadOnlyCollection<Guid>? AccountIds { get; init; }

    public IReadOnlyCollection<TransactionType>? Types { get; init; }

    /// <summary>When true, returns only deleted transactions (the recycle bin).</summary>
    public bool DeletedOnly { get; init; }

    public TransactionSort Sort { get; init; } = TransactionSort.DateDescending;

    /// <summary>1-based page number.</summary>
    public int Page { get; init; } = 1;

    public int PageSize { get; init; } = 50;
}

public sealed record PagedResult<T>(IReadOnlyList<T> Items, int TotalCount, int Page, int PageSize)
{
    public int PageCount => PageSize <= 0 ? 0 : (int)Math.Ceiling(TotalCount / (double)PageSize);
}

/// <summary>Totals for a filtered transaction set. Transfers are counted but never added to income or expense.</summary>
public sealed record TransactionSummary(int Count, long Income, long Expense)
{
    public long Net => checked(Income - Expense);
}

/// <summary>Income and expense totals for a period. Transfers and adjustments are never included.</summary>
public sealed record IncomeExpenseTotals(long Income, long Expense)
{
    public long Net => checked(Income - Expense);
}
